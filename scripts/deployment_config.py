"""Bootstrap with container Python; consume Compose's parsed JSON without logging secrets."""

import argparse
import json
import os
import re
import secrets
import socket
import sys
from pathlib import Path

from prepare_env import SECRET_LENGTHS, prepare_environment, storage_configuration, write_private


def initialize(root, port=None, project=None):
    for path in (root / ".env", root / ".local", root / ".local/seaweedfs", root / ".local/demo"):
        if path.is_symlink():
            raise ValueError("Symlink in local configuration; refusing root writes")
    env = root / ".env"
    if env.exists():
        if not env.is_file():
            raise ValueError("Expected a regular .env file")
        os.chmod(env, 0o600)
        return
    port = port or 8080
    project = project or "video-service"
    if not 1024 <= port <= 65535 or not re.fullmatch(r"[a-z][a-z0-9_-]{0,45}", project):
        raise ValueError("Invalid port or project name")
    content = (root / ".env.example").read_text()
    for key, length in SECRET_LENGTHS.items():
        content = content.replace(f"{key}=\n", f"{key}={secrets.token_hex(length)}\n")
    content = content.replace("WEB_PORT=8080", f"WEB_PORT={port}")
    content = content.replace("http://localhost:8080", f"http://localhost:{port}")
    write_private(env, content + f"\nCOMPOSE_PROJECT_NAME={project}\n", exclusive=True)


def configure(root, config, port=None, project=None):
    actual_project = config["name"]
    services = config["services"]
    values = services["storage-init"]["environment"]
    api = services["api"]["environment"]
    for key in ("POSTGRES_PASSWORD", "S3_ACCESS_KEY", "S3_SECRET_KEY", "S3_BUCKET"):
        if values[key] != api[key]:
            raise ValueError("Inconsistent service credentials")
    ports = services["web"]["ports"]
    if len(ports) != 1 or ports[0]["host_ip"] != "127.0.0.1":
        raise ValueError("Only loopback web publication is supported")
    actual_port = int(ports[0]["published"])
    if api["APP_ORIGIN"] != f"http://localhost:{actual_port}":
        raise ValueError("Local origin must match web port")
    if (port is not None and port != actual_port) or (project and project != actual_project):
        raise ValueError("Existing configuration differs; existing secrets/configuration preserved")
    for name, service in services.items():
        if name != "web" and service.get("ports"):
            raise ValueError("Internal service has a published port")
    storage_path = root / ".local/seaweedfs/s3.json"
    if storage_path.exists():
        if storage_path.is_symlink() or json.loads(
            storage_path.read_text()
        ) != storage_configuration(values):
            raise ValueError(
                "Existing S3 configuration differs; restore matching configuration manually"
            )
    prepare_environment(root, resolved_values=values, quiet=True)
    # The pinned SeaweedFS entrypoint drops to seaweed uid/gid 1000. Keep 0600
    # while allowing that process to read a config generated by root.
    if os.geteuid() == 0:
        os.chown(root / ".local/seaweedfs/s3.json", 1000, 1000)
    directory = root / ".local/demo"
    directory.mkdir(mode=0o700, exist_ok=True)
    os.chmod(directory, 0o700)
    return actual_project, actual_port


def check_port(port):
    with socket.socket() as connection:
        connection.bind(("127.0.0.1", port))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["init", "configure", "port"])
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--port", type=int)
    parser.add_argument("--project")
    args = parser.parse_args()
    try:
        if args.action == "init":
            initialize(args.root, args.port, args.project)
        elif args.action == "configure":
            project, port = configure(args.root, json.load(sys.stdin), args.port, args.project)
            print(f"{project} {port}")
        else:
            check_port(args.port)
    except Exception:
        raise SystemExit(
            "Configuration/port check failed; values hidden; existing data preserved"
        ) from None


if __name__ == "__main__":
    main()
