// Run with playwright-core and Chromium; creates a synthetic account, prints no credentials.
const { chromium } = require('playwright-core');
const { randomUUID } = require('node:crypto');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage();
  const username = 'browser_' + randomUUID().replaceAll('-', '').slice(0, 12);
  const email = username + '@example.com';
  const password = randomUUID();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:8080/register');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Имя пользователя').fill(username);
  await page.getByLabel('Пароль').fill(password);
  await page.getByRole('button', {name: 'Зарегистрироваться'}).click();
  await page.getByRole('button', {name: 'Выйти', exact: true}).waitFor();
  console.log('OK browser registration');
  await page.reload();
  await page.getByRole('button', {name: 'Выйти', exact: true}).waitFor();
  if (!(await page.locator('.account').innerText()).includes(username)) throw new Error('Session restore failed');
  const cookies = await page.context().cookies();
  const cookie = cookies.find(c => c.name === 'session_id');
  if (!cookie || !cookie.httpOnly || cookie.sameSite !== 'Lax') throw new Error('Cookie attributes failed');
  if (await page.evaluate(() => localStorage.length + sessionStorage.length)) throw new Error('Unexpected web storage');
  console.log('OK browser session restored and HttpOnly cookie');
  await page.getByRole('button', {name: 'Выйти', exact: true}).click();
  await page.getByRole('link', {name: 'Войти', exact: true}).waitFor();
  console.log('OK browser logout');
  await page.getByRole('link', {name: 'Войти', exact: true}).click();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Пароль').fill(password);
  await page.getByRole('button', {name: 'Войти', exact: true}).click();
  await page.getByRole('button', {name: 'Выйти', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Выйти', exact: true}).click();
  await page.getByRole('link', {name: 'Войти', exact: true}).waitFor();
  if (errors.length) throw new Error(errors.join('; '));
  console.log('OK browser login/logout; no JavaScript errors');
  await browser.close();
})().catch(error => { console.error(error.message); process.exit(1); });
