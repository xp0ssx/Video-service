// Synthetic media only. Run with playwright-core, Chromium and VIDEO_FIXTURE outside Git.
const {chromium} = require('playwright-core');
const {randomUUID} = require('node:crypto');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const base = 'http://localhost:8080';
(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--autoplay-policy=no-user-gesture-required']});
  const owner = await browser.newContext();
  const recipient = await browser.newContext();
  const guest = await browser.newContext();
  const page = await owner.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  try {
    await page.addInitScript(()=>{window.uploadProgressEvents=0;const send=XMLHttpRequest.prototype.send;XMLHttpRequest.prototype.send=function(...args){this.upload.addEventListener('progress',()=>window.uploadProgressEvents++);return send.apply(this,args)}});
    const username='video_'+randomUUID().replaceAll('-','').slice(0,12);
    const recipientName='grant_'+randomUUID().replaceAll('-','').slice(0,12);
    await page.goto(base+'/register');
    await page.getByLabel('Email',{exact:true}).fill(username+'@example.com');
    await page.getByLabel('Имя пользователя').fill(username);
    await page.getByLabel('Пароль').fill(randomUUID());
    await page.getByRole('button',{name:'Зарегистрироваться',exact:true}).click();
    await page.getByRole('button',{name:'Выйти',exact:true}).waitFor();
    const auth=await (await owner.request.get(base+'/api/auth/session')).json();
    const headers={'Origin':base,'X-CSRF-Token':auth.csrf_token};
    const registration=await recipient.request.post(base+'/api/auth/register',{headers:{Origin:base},data:{username:recipientName,email:recipientName+'@example.com',password:randomUUID()}});
    assert.equal(registration.status(),201);
    const file=process.env.VIDEO_FIXTURE || '/fixtures/input.mp4';
    const draft=await owner.request.post(base+'/api/videos',{headers,data:{title:'API synthetic upload',visibility:'public'}});
    assert.equal(draft.status(),201);
    const publicId=(await draft.json()).id;
    const upload=await owner.request.put(`${base}/api/videos/${publicId}/source`,{headers:{...headers,'Content-Type':'application/octet-stream'},data:fs.readFileSync(file)});
    assert.equal(upload.status(),202);
    await page.goto(base+'/upload');
    const title='Browser synthetic upload '+randomUUID().slice(0,8);
    await page.getByLabel('Название',{exact:true}).fill(title);
    await page.getByLabel('Описание',{exact:true}).fill('Synthetic FFmpeg clip; no copyrighted content.');
    await page.getByLabel('Доступ',{exact:true}).selectOption('private');
    await page.getByLabel('Видеофайл',{exact:true}).setInputFiles(file);
    await page.getByRole('button',{name:'Загрузить видео',exact:true}).click();
    const watch=page.getByRole('link',{name:'Смотреть готовое видео',exact:true});
    await watch.waitFor({timeout:90000});
    assert((await page.evaluate(()=>window.uploadProgressEvents))>0,'Real XHR progress events required');
    const href=await watch.getAttribute('href');
    const privateId=href.split('/').pop();
    console.log('OK browser/API upload -> real worker FFmpeg -> ready');
    const ranges=[];
    page.on('response',response=>{if(response.url().endsWith('/media'))ranges.push(response.status())});
    await watch.click();
    await page.locator('video').waitFor();
    await page.locator('video').evaluate(video=>{video.muted=true;return video.play()});
    await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.5);
    await page.locator('video').evaluate(video=>new Promise(resolve=>{video.addEventListener('seeked',resolve,{once:true});video.currentTime=8}));
    await page.waitForFunction(()=>{const video=document.querySelector('video');return video.currentTime>8.3&&!video.seeking&&video.readyState>=2});
    assert(ranges.includes(206),'Browser media Range must be served');
    const thumbnail=await owner.request.get(`${base}/api/videos/${privateId}/thumbnail`);
    assert.equal(thumbnail.status(),200);assert.equal((await thumbnail.body()).readUInt16BE(0),0xffd8);
    const partial=await owner.request.get(`${base}/api/videos/${privateId}/media`,{headers:{Range:'bytes=0-31'}});
    assert.equal(partial.status(),206);assert.equal((await partial.body()).length,32);
    assert.equal((await owner.request.head(`${base}/api/videos/${privateId}/media`)).status(),200);
    console.log('OK actual H.264/AAC playback, currentTime, seek, JPEG, HEAD and HTTP 206');
    for(const context of [guest,recipient])for(const suffix of ['','/media','/thumbnail'])assert.equal((await context.request.get(`${base}/api/videos/${privateId}${suffix}`)).status(),404);
    await page.goto(base+'/studio');
    const item=page.locator('article').filter({has:page.getByRole('heading',{name:title,exact:true})});
    await item.locator('summary').click();
    await item.getByLabel('Username получателя').fill(recipientName);
    await item.getByRole('button',{name:'Предоставить доступ',exact:true}).click();
    await item.getByRole('button',{name:'Отозвать доступ',exact:true}).waitFor();
    assert.equal((await recipient.request.get(`${base}/api/videos/${privateId}/media`,{headers:{Range:'bytes=0-15'}})).status(),206);
    const receivedPage=await recipient.newPage();
    await receivedPage.goto(base+href);
    await receivedPage.locator('video').evaluate(video=>{video.muted=true;return video.play()});
    await receivedPage.waitForFunction(()=>document.querySelector('video')?.currentTime>.5);
    await item.getByRole('button',{name:'Отозвать доступ',exact:true}).click();
    await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).some(button=>button.textContent==='Отозвать доступ'));
    assert.equal((await recipient.request.get(`${base}/api/videos/${privateId}/media`,{headers:{Range:'bytes=10-25'}})).status(),404);
    await receivedPage.reload();
    await receivedPage.getByRole('alert').filter({hasText:'Видео не найдено'}).waitFor();
    await item.getByLabel('Доступ',{exact:true}).selectOption('public');
    await item.getByRole('button',{name:'Сохранить',exact:true}).click();
    await item.locator('p').filter({hasText:'Публичное'}).waitFor();
    assert.equal((await guest.request.get(`${base}/api/videos/${privateId}/media`)).status(),200);
    await item.getByLabel('Доступ',{exact:true}).selectOption('private');
    await item.getByRole('button',{name:'Сохранить',exact:true}).click();
    await item.locator('p').filter({hasText:'Приватное'}).waitFor();
    assert.equal((await guest.request.head(`${base}/api/videos/${privateId}/media`)).status(),404);
    assert.equal((await guest.request.get(`${base}/api/videos/${publicId}/media`)).status(),200);
    assert.equal(errors.length,0,'Unexpected browser JavaScript errors');
    console.log('OK private owner/grantee/guest, UI grants and revocation, visibility changes and old media URL denial');
  } finally {await browser.close()}
})().catch(error=>{console.error(error.message);process.exit(1)});
